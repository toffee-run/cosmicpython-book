import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { load } from 'cheerio'
import { compilePage } from './content.mjs'
import customizations from '../content/customizations.mjs'

const base = process.env.BASE_PATH || '/'
const phrases = JSON.parse(await readFile('content/translations/phrases.json', 'utf8'))
const dictionary = {
  ...JSON.parse(await readFile('content/translations/dictionary.json', 'utf8')),
  ...JSON.parse(await readFile('content/translations/overrides.json', 'utf8')),
}
const preface = await readFile('content/book/preface.html', 'utf8')
const $ = load(preface)
const slugs = new Set($('#toc a').map((_, el) => $(el).attr('href').split('/').pop().replace('.html', '')).get())
await mkdir('src/generated', { recursive: true })
const manifest = []
const missing = {}
let total = 0, translated = 0
for (const slug of slugs) {
  const source = await readFile(`content/book/${slug}.html`, 'utf8')
  const result = compilePage(source, { dictionary, phrases, edits: customizations[slug], base, slugs })
  const { title, html, styles, words, contexts } = result
  manifest.push({ slug, title })
  total += result.total
  translated += result.translated
  for (const [word, count] of Object.entries(result.missing)) missing[word] = (missing[word] || 0) + count
  await writeFile(`src/generated/${slug}.json`, JSON.stringify({ title, html, styles, words, contexts, phrases: result.phrases }))
  await writeFile(`src/routes/${slug}[.]html.tsx`, `// Generated by scripts/prepare-content.mjs. Edit content/book/ instead.\nimport { createFileRoute } from '@tanstack/react-router'\nimport { BookPage } from '../components/BookPage'\nimport page from '../generated/${slug}.json'\nexport const Route = createFileRoute('/${slug}.html')({\n  head: () => ({ meta: [{ title: ${JSON.stringify(title)} }] }),\n  component: () => <BookPage page={page} />,\n})\n`)
}
await writeFile('src/generated/manifest.json', JSON.stringify(manifest, null, 2))
await writeFile('src/generated/translation-report.json', JSON.stringify({ total, translated, missing: Object.fromEntries(Object.entries(missing).sort((a,b) => b[1]-a[1])) }, null, 2))
console.log(`Prepared ${manifest.length} pages; translated ${translated}/${total} word occurrences (${(translated / total * 100).toFixed(2)}%).`)
